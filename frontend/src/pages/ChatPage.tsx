import { useEffect, useId, useRef, useState, type FormEvent } from 'react'
import {
  ApiError,
  asApiError,
  askQuestion,
  fetchLlmConfig,
  type AnswerResponse,
  type Grounding,
  type LlmConfig,
  type RetrievalRequest,
} from '../api'
import ChatAnswer from '../components/ChatAnswer'
import ErrorPanel from '../components/ErrorPanel'
import ModelOption from '../components/ModelOption'
import { EMBEDDING_MODELS } from '../data/embeddingModels'
import { EVALUATION_QUESTIONS } from '../data/researchResults'
import { PAGES } from '../navigation'
import {
  QUESTION_MAX_CHARACTERS,
  questionLength,
  questionProblem,
  TOP_K_DEFAULT,
  TOP_K_MAX,
  TOP_K_MIN,
} from '../retrievalSearch'
import { useSelectedModel } from '../state/modelSelection'

// The approved wording (docs/llm-and-rag.md), shown whenever Claude answers.
export const PRIVACY_NOTICE =
  "Answers are generated by Claude, a model hosted by Anthropic. Your question and retrieved NHS text are sent to Anthropic's API to generate each answer. Avoid entering personal or identifying health information. This tool provides general information, not medical advice. In an emergency, call 999."

type ConfigOutcome =
  | { attempt: number; kind: 'loaded'; config: LlmConfig }
  | { attempt: number; kind: 'failed'; error: ApiError }

type Asked =
  | { kind: 'loading'; request: RetrievalRequest }
  | { kind: 'loaded'; request: RetrievalRequest; response: AnswerResponse }
  | { kind: 'failed'; request: RetrievalRequest; error: ApiError }

// Announced to screen readers when an answer arrives.
const GROUNDING_STATUS: Record<Grounding, string> = {
  grounded: 'supported by the retrieved sources',
  partly_grounded: 'partly supported by the retrieved sources',
  not_grounded: 'not supported by the retrieved sources',
  not_enough_evidence: 'not enough evidence to answer',
  refused: 'the language model declined to answer',
}

const TOP_K_CHOICES =Array.from({ length: TOP_K_MAX - TOP_K_MIN + 1 }, (_, i) => TOP_K_MIN + i)

// One question, one answer. Questions are not kept in the address, so a refresh or a shared
// link never sends a question (which can cost money with a hosted model), and each question is
// answered on its own: no earlier questions or answers are sent with it.
function ChatPage() {
  const { selectedModel, selectModel } = useSelectedModel()

  // Which LLM the backend uses decides whether the privacy notice is shown, so questions can be
  // sent only once it is known.
  const [configAttempt, setConfigAttempt] = useState(0)
  const [configOutcome, setConfigOutcome] = useState<ConfigOutcome | null>(null)
  useEffect(() => {
    const controller = new AbortController()
    fetchLlmConfig(controller.signal)
      .then((config) => {
        if (!controller.signal.aborted) setConfigOutcome({ attempt: configAttempt, kind: 'loaded', config })
      })
      .catch((error: unknown) => {
        if (!controller.signal.aborted) {
          const failure = asApiError(error, 'Something went wrong while contacting the backend.')
          setConfigOutcome({ attempt: configAttempt, kind: 'failed', error: failure })
        }
      })
    return () => controller.abort()
  }, [configAttempt])
  const config = configOutcome?.attempt === configAttempt ? configOutcome : null

  const [question, setQuestion] = useState('')
  const [topK, setTopK] = useState(TOP_K_DEFAULT)
  const [asked, setAsked] = useState<Asked | null>(null)
  const controllerRef = useRef<AbortController | null>(null)
  useEffect(() => () => controllerRef.current?.abort(), [])

  function ask(request: RetrievalRequest) {
    controllerRef.current?.abort()
    const controller = new AbortController()
    controllerRef.current = controller
    setAsked({ kind: 'loading', request })
    askQuestion(request, controller.signal)
      .then((response) => {
        if (!controller.signal.aborted) setAsked({ kind: 'loaded', request, response })
      })
      .catch((error: unknown) => {
        if (!controller.signal.aborted) {
          const failure = asApiError(error, 'Something went wrong while answering the question.')
          setAsked({ kind: 'failed', request, error: failure })
        }
      })
  }

  const loading = asked?.kind === 'loading'
  const problem = questionProblem(question)
  const length = questionLength(question)
  const reason =
    config === null
      ? 'Checking which language model the backend uses…'
      : config.kind === 'failed'
        ? 'Waiting for the backend.'
        : !selectedModel
          ? 'Choose an embedding model.'
          : problem
  const questionRef = useRef<HTMLTextAreaElement>(null)
  const ids = { question: useId(), counter: useId(), reason: useId(), topK: useId(), notice: useId() }

  function submit(event: FormEvent) {
    event.preventDefault()
    if (reason || !selectedModel || loading) {
      return
    }
    ask({ question: question.trim(), model: selectedModel.id, topK })
  }

  function fillExample(text: string) {
    setQuestion(text)
    questionRef.current?.focus()
  }

  // The notice also follows the answer, in case the backend was restarted with another provider.
  const usesClaude =
    (config?.kind === 'loaded' && config.config.provider === 'claude') ||
    (asked?.kind === 'loaded' && asked.response.llm.provider === 'claude')
  const usesMock = config?.kind === 'loaded' && config.config.provider === 'mock'

  const status = loading
    ? 'Retrieving chunks and generating an answer…'
    : asked?.kind === 'loaded'
      ? `Answer ready: ${GROUNDING_STATUS[asked.response.grounding]}.`
      : ''

  return (
    <>
      <p className="page-purpose">{PAGES.chat.purpose}</p>

      {usesClaude && (
        <section className="notice" aria-labelledby={ids.notice}>
          <h2 id={ids.notice}>Privacy</h2>
          <p>{PRIVACY_NOTICE}</p>
        </section>
      )}
      {usesMock && (
        <p className="config-panel chat-mode">
          The backend is using the mock provider: answers are placeholders that quote the start
          of the top retrieved chunk, made without a language model. Nothing leaves this computer.
        </p>
      )}
      {config?.kind === 'failed' && (
        <ErrorPanel
          title="Could not check the language model"
          error={config.error}
          onRetry={() => setConfigAttempt((n) => n + 1)}
        />
      )}

      <form className="retrieval-form" onSubmit={submit} noValidate>
        <div className="field field-wide">
          <label htmlFor={ids.question}>Question</label>
          <textarea
            id={ids.question}
            ref={questionRef}
            rows={3}
            value={question}
            onChange={(event) => setQuestion(event.target.value)}
            aria-describedby={ids.counter}
            aria-invalid={length > QUESTION_MAX_CHARACTERS}
          />
          <span
            id={ids.counter}
            className={length > QUESTION_MAX_CHARACTERS ? 'counter counter-over' : 'counter'}
          >
            {length.toLocaleString('en-GB')} / {QUESTION_MAX_CHARACTERS.toLocaleString('en-GB')}{' '}
            characters
          </span>
        </div>

        <details className="examples">
          <summary>Example questions from the research evaluation</summary>
          <ul className="example-list">
            {EVALUATION_QUESTIONS.map((example) => (
              <li key={example.id}>
                <button
                  type="button"
                  className="example-button"
                  onClick={() => fillExample(example.question)}
                >
                  {example.question}
                </button>
              </li>
            ))}
          </ul>
        </details>

        <fieldset className="model-picker">
          <legend>Embedding model</legend>
          {!selectedModel && <p className="section-note">Choose a model to retrieve chunks with.</p>}
          <div className="card-grid">
            {EMBEDDING_MODELS.map((model) => (
              <ModelOption
                key={model.id}
                model={model}
                checked={selectedModel?.id === model.id}
                onSelect={selectModel}
              />
            ))}
          </div>
          <p className="section-note">
            The choice is shared with the Retrieval page and Model Lab and saved in this browser.
          </p>
        </fieldset>

        <div className="form-actions">
          <div className="field">
            <label htmlFor={ids.topK}>Number of chunks</label>
            <select
              id={ids.topK}
              value={topK}
              onChange={(event) => setTopK(Number(event.target.value))}
            >
              {TOP_K_CHOICES.map((choice) => (
                <option key={choice} value={choice}>
                  {choice}
                </option>
              ))}
            </select>
          </div>
          <button
            type="submit"
            className="button-primary"
            disabled={reason !== null || loading}
            aria-describedby={reason ? ids.reason : undefined}
          >
            Ask
          </button>
          {reason && (
            <p id={ids.reason} className="form-reason">
              {reason}
            </p>
          )}
        </div>
        <p className="section-note">
          Each question is answered on its own; earlier questions and answers are not sent.
        </p>
      </form>

      <p className="visually-hidden" role="status">
        {status}
      </p>

      {loading && (
        <div className="config-panel retrieval-status">
          <p className="status-line">Answering…</p>
          <p>
            Retrieving chunks, then generating an answer from them. The first question for an
            embedding model can take several seconds while the model loads.
          </p>
        </div>
      )}

      {asked?.kind === 'failed' && (
        <ErrorPanel
          title={asked.error.kind === 'invalid' ? 'The question was not accepted' : 'No answer'}
          error={asked.error}
          onRetry={asked.error.kind === 'invalid' ? undefined : () => ask(asked.request)}
        />
      )}

      {asked?.kind === 'loaded' && <ChatAnswer key={asked.response.question} response={asked.response} />}
    </>
  )
}

export default ChatPage
