import BarChart from '../components/BarChart'
import EvaluationDatasetSection from '../components/EvaluationDatasetSection'
import StatCard from '../components/StatCard'
import { EMBEDDING_MODELS, type ModelId } from '../data/embeddingModels'
import {
  ARTICLE_COUNT,
  ASTHMA_QUESTION_COUNT,
  DIFFERING_QUESTIONS,
  IMPERFECT_QUESTIONS,
  QUESTION_COUNT,
  questionsWhereModelsDiffer,
  resultFor,
} from '../data/researchFindings'
import {
  EVALUATION_QUESTIONS,
  INDEX_BUILDS,
  LATER_RUN_MEAN_GENERATION_SECONDS,
  RAG_LATENCY,
  RETRIEVAL_SUMMARY,
  type RetrievalScores,
} from '../data/researchResults'
import { formatDecimal, rankLabel } from '../format'
import { PAGES } from '../navigation'
import { useSelectedModel } from '../state/modelSelection'

// Every table and chart lists the models in the same order as the Model Lab.
const MODEL_ORDER: ModelId[] = EMBEDDING_MODELS.map((model) => model.id)

const METRICS: { key: keyof RetrievalScores; label: string; decimals: number }[] = [
  { key: 'precisionAt5', label: 'Precision@5', decimals: 2 },
  { key: 'recallAt5', label: 'Recall@5', decimals: 2 },
  { key: 'mrrAt5', label: 'MRR@5', decimals: 2 },
  { key: 'ndcgAt5', label: 'nDCG@5', decimals: 3 },
]

const PRECISION = METRICS[0]
const MRR = METRICS[2]
const NDCG = METRICS[3]

function scoresFor(model: ModelId) {
  return RETRIEVAL_SUMMARY.find((row) => row.model === model)!
}

function latency(stage: string) {
  return RAG_LATENCY.find((row) => row.stage === stage)!
}

function listQuestions(ids: number[]) {
  return ids.length === 1 ? `question ${ids[0]}` : `questions ${ids.slice(0, -1).join(', ')} and ${ids.at(-1)}`
}

function AnalyticsPage() {
  const { selectedModel } = useSelectedModel()
  const isSelected = (model: ModelId) => selectedModel?.id === model

  const chartBars = (metric: (typeof METRICS)[number]) =>
    MODEL_ORDER.map((model) => ({
      label: model,
      value: scoresFor(model)[metric.key],
      displayValue: formatDecimal(scoresFor(model)[metric.key], metric.decimals),
      exactValue: String(scoresFor(model)[metric.key]),
      emphasised: isSelected(model),
    }))

  const retrieval = latency('Retrieval Time')
  const generation = latency('Generation Time')
  const total = latency('Total Response Time')
  const mpnetVsBge = questionsWhereModelsDiffer('MPNet', 'BGE')

  return (
    <>
      <p className="page-purpose">{PAGES.analytics.purpose}</p>

      <section className="notice" aria-labelledby="provenance-heading">
        <h2 id="provenance-heading">Historical research results, not generated by this app</h2>
        <p>
          Every figure on this page comes from the original dissertation research (Google Colab
          notebooks, saved in <code>Healthcare_RAG/results</code>). MedQuery displays them as they
          were recorded and recalculates nothing. The evaluation used {QUESTION_COUNT} questions
          and retrieved the top 5 chunks for each.
        </p>
      </section>

      <section className="dashboard-section" aria-labelledby="comparison-heading">
        <h2 id="comparison-heading">Retrieval comparison</h2>
        <p className="section-note">
          Mean over {QUESTION_COUNT} questions. Higher is better for every metric. Values are
          rounded for display; the exact values are listed further down.
        </p>
        <div className="table-scroll">
          <table className="data-table">
            <thead>
              <tr>
                <th scope="col">Model</th>
                {METRICS.map((metric) => (
                  <th key={metric.key} scope="col" className="numeric">
                    {metric.label}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              {MODEL_ORDER.map((model) => (
                <tr key={model} data-selected={isSelected(model) ? 'true' : undefined}>
                  <th scope="row">
                    {model}
                    {isSelected(model) && <span className="row-tag">Selected</span>}
                  </th>
                  {METRICS.map((metric) => (
                    <td key={metric.key} className="numeric">
                      {formatDecimal(scoresFor(model)[metric.key], metric.decimals)}
                    </td>
                  ))}
                </tr>
              ))}
            </tbody>
          </table>
        </div>
        <p className="section-note after-table">
          BGE and E5 scored identically on every question. MPNet&apos;s lead over them comes from{' '}
          {listQuestions(mpnetVsBge)} alone, which is too little evidence to call it the better
          model.
        </p>
      </section>

      <section className="dashboard-section" aria-labelledby="charts-heading">
        <h2 id="charts-heading">Ranking quality</h2>
        <p className="section-note">
          {PRECISION.label} and Recall@5 appear in the table only: with one relevant article per
          question, Precision@5 cannot exceed 0.20, and neither varies enough to chart usefully.
          Hover over or focus a bar to see its exact value.
        </p>
        <div className="chart-grid">
          <BarChart
            title={MRR.label}
            subtitle="Mean reciprocal rank of the relevant article, scale 0–1"
            bars={chartBars(MRR)}
            max={1}
          />
          <BarChart
            title={NDCG.label}
            subtitle="Normalised discounted cumulative gain, scale 0–1"
            bars={chartBars(NDCG)}
            max={1}
          />
        </div>
      </section>

      <section className="dashboard-section" aria-labelledby="questions-heading">
        <h2 id="questions-heading">Results per question</h2>
        <p className="section-note">
          Where each model ranked the relevant article among its top 5 results. Every model ranked
          it first on {QUESTION_COUNT - IMPERFECT_QUESTIONS.length} of {QUESTION_COUNT} questions.
          Lower rankings occurred on {listQuestions(IMPERFECT_QUESTIONS)}, and the models only
          differ on {listQuestions(DIFFERING_QUESTIONS)}.
        </p>
        <div className="table-scroll">
          <table className="data-table">
            <thead>
              <tr>
                <th scope="col" className="numeric">
                  #
                </th>
                <th scope="col">Question</th>
                <th scope="col">Relevant article</th>
                {MODEL_ORDER.map((model) => (
                  <th key={model} scope="col" data-selected={isSelected(model) ? 'true' : undefined}>
                    {model}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              {EVALUATION_QUESTIONS.map((q) => (
                <tr key={q.id}>
                  <td className="numeric">{q.id}</td>
                  <th scope="row">{q.question}</th>
                  <td>
                    <code>{q.relevantArticle}</code>
                  </td>
                  {MODEL_ORDER.map((model) => {
                    const result = resultFor(model, q.id)
                    return (
                      <td
                        key={model}
                        className={result < 1 ? 'rank rank-low' : 'rank'}
                        data-selected={isSelected(model) ? 'true' : undefined}
                      >
                        {rankLabel(result)}
                      </td>
                    )
                  })}
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </section>

      <section className="dashboard-section" aria-labelledby="speed-heading">
        <h2 id="speed-heading">Speed: one research run</h2>
        <p className="section-note">
          MPNet + Llama 3.1 8B Instruct, top-k = 5, the {QUESTION_COUNT} evaluation questions, on
          Google Colab (notebook 06 reports a Tesla T4 GPU). This is one specific run, not a
          general benchmark: timings depend on hardware and vary between runs.
        </p>
        <div className="card-grid">
          <StatCard
            label="Retrieval (mean)"
            value={`${formatDecimal(retrieval.meanSeconds, 4)} s`}
            detail={`Range ${retrieval.minSeconds}–${retrieval.maxSeconds} s`}
            source="rag_performance_summary.csv"
          />
          <StatCard
            label="Answer generation (mean)"
            value={`${formatDecimal(generation.meanSeconds, 2)} s`}
            detail={`Range ${generation.minSeconds}–${generation.maxSeconds} s`}
            source="rag_performance_summary.csv"
          />
          <StatCard
            label="Total response (mean)"
            value={`${formatDecimal(total.meanSeconds, 2)} s`}
            detail={`Range ${total.minSeconds}–${total.maxSeconds} s`}
            source="rag_performance_summary.csv"
          />
        </div>
        <p className="section-note after-table">
          A later run of the same setup (saved in <code>formal_rag_evaluation_data.json</code>)
          recorded a mean generation time of {formatDecimal(LATER_RUN_MEAN_GENERATION_SECONDS, 2)} s,
          which shows how much timings vary between runs.
        </p>

        <h3 className="subsection-heading">Index build time</h3>
        <div className="table-scroll">
          <table className="data-table">
            <thead>
              <tr>
                <th scope="col">Model</th>
                <th scope="col" className="numeric">
                  Vectors
                </th>
                <th scope="col" className="numeric">
                  Dimensions
                </th>
                <th scope="col">Index</th>
                <th scope="col" className="numeric">
                  Build time (s)
                </th>
              </tr>
            </thead>
            <tbody>
              {MODEL_ORDER.map((model) => {
                const build = INDEX_BUILDS.find((row) => row.model === model)!
                return (
                  <tr key={model} data-selected={isSelected(model) ? 'true' : undefined}>
                    <th scope="row">{model}</th>
                    <td className="numeric">{build.vectors.toLocaleString('en-GB')}</td>
                    <td className="numeric">{build.dimension}</td>
                    <td>{build.indexType}</td>
                    <td className="numeric">{build.buildTimeSeconds}</td>
                  </tr>
                )
              })}
            </tbody>
          </table>
        </div>
        <p className="stat-source">Source: faiss_experimental_summary.csv</p>
      </section>

      <details className="exact-values">
        <summary>Exact values from the source files</summary>
        <div className="table-scroll">
          <table className="data-table">
            <caption>retrieval_model_comparison.csv</caption>
            <thead>
              <tr>
                <th scope="col">Model</th>
                {METRICS.map((metric) => (
                  <th key={metric.key} scope="col" className="numeric">
                    {metric.label}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              {MODEL_ORDER.map((model) => (
                <tr key={model}>
                  <th scope="row">{model}</th>
                  {METRICS.map((metric) => (
                    <td key={metric.key} className="numeric">
                      {String(scoresFor(model)[metric.key])}
                    </td>
                  ))}
                </tr>
              ))}
            </tbody>
          </table>
        </div>
        <div className="table-scroll">
          <table className="data-table">
            <caption>rag_performance_summary.csv (seconds)</caption>
            <thead>
              <tr>
                <th scope="col">Stage</th>
                <th scope="col" className="numeric">
                  Mean
                </th>
                <th scope="col" className="numeric">
                  Std dev
                </th>
                <th scope="col" className="numeric">
                  Min
                </th>
                <th scope="col" className="numeric">
                  Max
                </th>
              </tr>
            </thead>
            <tbody>
              {RAG_LATENCY.map((row) => (
                <tr key={row.stage}>
                  <th scope="row">{row.stage}</th>
                  <td className="numeric">{String(row.meanSeconds)}</td>
                  <td className="numeric">{String(row.stdDevSeconds)}</td>
                  <td className="numeric">{String(row.minSeconds)}</td>
                  <td className="numeric">{String(row.maxSeconds)}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </details>

      <section className="dashboard-section" aria-labelledby="metrics-heading">
        <h2 id="metrics-heading">What the metrics mean</h2>
        <dl className="definition-list">
          <dt>Precision@5</dt>
          <dd>
            Of the top 5 results, the share that come from the relevant article (each article
            counted once). With one relevant article per question, the maximum is 0.20.
          </dd>
          <dt>Recall@5</dt>
          <dd>
            Whether the relevant article appears anywhere in the top 5 (1 = found, 0 = missed),
            averaged over the questions.
          </dd>
          <dt>MRR@5 (mean reciprocal rank)</dt>
          <dd>
            1 divided by the position of the first result from the relevant article: 1st place
            scores 1, 2nd scores 0.5, 3rd scores 0.33, and 0 if it is not in the top 5. Averaged
            over the questions. Only the top 5 were retrieved, hence “@5”.
          </dd>
          <dt>nDCG@5 (normalised discounted cumulative gain)</dt>
          <dd>
            Also rewards finding the relevant article near the top, but lower positions are
            penalised more gently than in MRR@5: 2nd place scores 0.63 instead of 0.5.
          </dd>
        </dl>
      </section>

      <section className="dashboard-section" aria-labelledby="limitations-heading">
        <h2 id="limitations-heading">Limitations</h2>
        <ul className="limitations-list">
          <li>
            <strong>Small test set:</strong> {QUESTION_COUNT} questions covering {ARTICLE_COUNT}{' '}
            articles, {ASTHMA_QUESTION_COUNT} of them about asthma.
          </li>
          <li>
            <strong>One relevant article per question</strong>, judged per article rather than per
            chunk, so Precision@5 is capped at 0.20.
          </li>
          <li>
            <strong>Only the top 5 results were evaluated</strong>, so the ranking metric is
            MRR@5: an article ranked 6th counts the same as one never found.
          </li>
          <li>
            <strong>Differences rest on very few questions:</strong> lower rankings occurred on only{' '}
            {IMPERFECT_QUESTIONS.length} questions, and the models differ on just{' '}
            {DIFFERING_QUESTIONS.length}. BGE and E5 are identical on every question, and MPNet
            leads them by {mpnetVsBge.length} question. The ranking is not statistically reliable.
          </li>
          <li>
            <strong>Timings come from specific Colab runs</strong> and cannot be compared with other
            hardware; two runs of the same setup gave different results.
          </li>
          <li>
            <strong>Answer quality was not measured:</strong> no faithfulness, relevance or
            correctness scores were saved, only retrieval metrics and timings.
          </li>
        </ul>
      </section>

      <EvaluationDatasetSection />
    </>
  )
}

export default AnalyticsPage
