import { render, screen, within } from '@testing-library/react'
import { MemoryRouter } from 'react-router'
import { describe, expect, it } from 'vitest'
import App from '../App'
import { STORAGE_KEY } from '../state/modelSelection'

function renderAnalytics() {
  render(
    <MemoryRouter initialEntries={['/analytics']}>
      <App />
    </MemoryRouter>,
  )
}

function section(name: string | RegExp) {
  return within(screen.getByRole('region', { name }))
}

// The text of each body row of a table, cell by cell.
function bodyRows(table: HTMLElement) {
  return Array.from(table.querySelectorAll('tbody tr')).map((row) =>
    Array.from(row.querySelectorAll('th, td')).map((cell) => cell.textContent),
  )
}

describe('Analytics', () => {
  it('labels the results as historical research and uses MRR@5', () => {
    renderAnalytics()

    expect(
      screen.getByRole('heading', { name: 'Historical research results, not generated by this app' }),
    ).toBeInTheDocument()
    const table = section('Retrieval comparison').getByRole('table')
    const headers = within(table)
      .getAllByRole('columnheader')
      .map((cell) => cell.textContent)
    expect(headers).toEqual(['Model', 'Precision@5', 'Recall@5', 'MRR@5', 'nDCG@5'])
    expect(document.body.textContent).not.toMatch(/MRR(?!@5)/)
  })

  it('shows the retrieval comparison, rounded only for display', () => {
    renderAnalytics()

    const table = section('Retrieval comparison').getByRole('table')
    expect(bodyRows(table)).toEqual([
      ['MPNet', '0.20', '1.00', '0.95', '0.963'],
      ['MiniLM', '0.18', '0.90', '0.80', '0.826'],
      ['BGE', '0.20', '1.00', '0.90', '0.926'],
      ['E5', '0.20', '1.00', '0.90', '0.926'],
    ])
    // The exact values are still available on the page.
    const exact = within(screen.getByText('Exact values from the source files').closest('details')!)
    expect(exact.getByText('0.9630929753571458')).toBeInTheDocument()
    expect(exact.getByText('0.0033455775120132683')).toBeInTheDocument()
  })

  it('draws MRR@5 and nDCG@5 charts with a labelled value on every bar', () => {
    renderAnalytics()

    const barsIn = (title: string) =>
      within(screen.getByRole('figure', { name: title })).getAllByRole('listitem')
    // The visible label and value of each bar.
    const visible = (bars: HTMLElement[]) =>
      bars.map((bar) => `${bar.querySelector('.bar-label')!.textContent} ${bar.querySelector('.bar-value')!.textContent}`)

    expect(visible(barsIn('MRR@5'))).toEqual(['MPNet 0.95', 'MiniLM 0.80', 'BGE 0.90', 'E5 0.90'])
    expect(visible(barsIn('nDCG@5'))).toEqual(['MPNet 0.963', 'MiniLM 0.826', 'BGE 0.926', 'E5 0.926'])

    // Hovering or focusing a bar reveals its exact, unrounded value.
    expect(barsIn('nDCG@5')[0].querySelector('.bar-tooltip')).toHaveTextContent('0.9630929753571458')
  })

  it('shows every question, the limitations and the specific latency run', () => {
    renderAnalytics()

    const questions = section('Results per question').getByRole('table')
    const rows = bodyRows(questions)
    expect(rows).toHaveLength(10)
    expect(rows[6]).toEqual([
      '7',
      'What is amoxicillin used for?',
      'amoxicillin.txt',
      '1st',
      'Not in top 5',
      '2nd',
      '2nd',
    ])

    const limitations = section('Limitations')
    expect(limitations.getByText(/10 questions covering 8 articles, 3 of them about asthma/)).toBeInTheDocument()
    expect(limitations.getByText(/capped at 0\.20/)).toBeInTheDocument()
    expect(limitations.getByText(/lower rankings occurred on only 3 questions, and the models differ on just 2/)).toBeInTheDocument()
    expect(limitations.getByText(/BGE and E5 are identical on every question, and MPNet leads them by 1 question/)).toBeInTheDocument()

    const speed = section('Speed: one research run')
    expect(speed.getByText(/MPNet \+ Llama 3\.1 8B Instruct, top-k = 5/)).toBeInTheDocument()
    expect(speed.getByText(/not a general benchmark/)).toBeInTheDocument()
  })

  it("highlights the model selected in the Model Lab", () => {
    localStorage.setItem(STORAGE_KEY, 'BGE')
    renderAnalytics()

    const table = section('Retrieval comparison').getByRole('table')
    const bgeRow = within(table).getByRole('rowheader', { name: /^BGE/ }).closest('tr')!
    expect(bgeRow).toHaveAttribute('data-selected', 'true')
    expect(within(bgeRow).getByText('Selected')).toBeInTheDocument()
    expect(within(table).getAllByText('Selected')).toHaveLength(1)

    const mrrBars = within(screen.getByRole('figure', { name: 'MRR@5' })).getAllByRole('listitem')
    expect(mrrBars.map((bar) => bar.getAttribute('data-muted'))).toEqual(['true', 'true', null, 'true'])
  })
})
